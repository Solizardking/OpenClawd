#!/usr/bin/env node
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const repoRoot = path.resolve(new URL('..', import.meta.url).pathname);
const sourceRoot = path.join(repoRoot, 'payments/pay-main/typescript/packages/solana-pay');
const defaultOutDir = path.join(repoRoot, 'generated/merchants');

const help = `OpenClawd Solana merchant generator

Usage:
  npm run payments:merchant -- create <name> [options]

Options:
  --type <pos|merchant|both>       Template to include. Default: both
  --output <dir>                   Output directory. Default: generated/merchants
  --recipient <wallet>             Merchant Solana wallet for docs/config
  --label <name>                   Store label. Default: <name>
  --cluster <devnet|mainnet-beta>  Target cluster hint. Default: devnet
  --force                          Overwrite an existing generated project

Examples:
  npm run payments:merchant -- create taco-stand --recipient 11111111111111111111111111111111 --label "Taco Stand"
  npm run payments:merchant -- create api-store --type merchant --output ./apps
`;

function parseArgs(argv) {
  const [command, name, ...rest] = argv;
  const options = {
    command,
    name,
    type: 'both',
    output: defaultOutDir,
    recipient: '11111111111111111111111111111111',
    label: name,
    cluster: 'devnet',
    force: false,
  };

  for (let i = 0; i < rest.length; i += 1) {
    const arg = rest[i];
    if (arg === '--force') {
      options.force = true;
      continue;
    }

    if (!arg.startsWith('--')) {
      throw new Error(`Unexpected argument: ${arg}`);
    }

    const key = arg.slice(2);
    const value = rest[i + 1];
    if (!value || value.startsWith('--')) {
      throw new Error(`Missing value for ${arg}`);
    }
    i += 1;

    if (key === 'type') options.type = value;
    else if (key === 'output') options.output = path.resolve(value);
    else if (key === 'recipient') options.recipient = value;
    else if (key === 'label') options.label = value;
    else if (key === 'cluster') options.cluster = value;
    else throw new Error(`Unknown option: ${arg}`);
  }

  return options;
}

function slugify(input) {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);
}

function includeForType(type) {
  if (type === 'pos') return ['point-of-sale'];
  if (type === 'merchant') return ['payment-flow-merchant'];
  if (type === 'both') return ['point-of-sale', 'payment-flow-merchant'];
  throw new Error('--type must be one of: pos, merchant, both');
}

async function copyTemplate(options, appName) {
  const targetRoot = path.join(options.output, appName);
  await mkdir(targetRoot, { recursive: true });

  const solanaPayRoot = path.join(targetRoot, 'solana-pay');
  await cp(path.join(sourceRoot, 'core'), path.join(solanaPayRoot, 'core'), {
    recursive: true,
    force: options.force,
    errorOnExist: !options.force,
    filter: (src) => !src.includes('node_modules') && !src.includes('/dist') && !src.includes('/.next'),
  });

  for (const example of includeForType(options.type)) {
    await cp(path.join(sourceRoot, 'examples', example), path.join(solanaPayRoot, 'examples', example), {
      recursive: true,
      force: options.force,
      errorOnExist: !options.force,
      filter: (src) => !src.includes('node_modules') && !src.includes('/.next'),
    });
  }

  await writeProjectFiles(targetRoot, options, appName);
  await patchGeneratedPackages(targetRoot, options, appName);
  return targetRoot;
}

async function writeProjectFiles(targetRoot, options, appName) {
  const hasPos = includeForType(options.type).includes('point-of-sale');
  const hasMerchant = includeForType(options.type).includes('payment-flow-merchant');
  const scripts = {
    'install:templates': [
      hasPos ? 'pnpm --dir solana-pay/examples/point-of-sale install' : undefined,
      hasMerchant ? 'pnpm --dir solana-pay/examples/payment-flow-merchant install' : undefined,
    ].filter(Boolean).join(' && '),
    build: [
      'pnpm --dir solana-pay/core build',
      hasPos ? 'pnpm --dir solana-pay/examples/point-of-sale build' : undefined,
    ].filter(Boolean).join(' && '),
  };
  if (hasPos) {
    scripts['pos:dev'] = 'pnpm --dir solana-pay/examples/point-of-sale dev';
    scripts['pos:proxy'] = 'pnpm --dir solana-pay/examples/point-of-sale proxy';
  }
  if (hasMerchant) {
    scripts['merchant:start'] = 'pnpm --dir solana-pay/examples/payment-flow-merchant start';
  }

  const packageJson = {
    name: `@openclawdsolana/${appName}-merchant`,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: `${options.label} Solana merchant kit generated by OpenClawd`,
    scripts,
    openclawd: {
      kind: 'solana-merchant',
      source: 'payments/pay-main',
      templates: includeForType(options.type),
    },
    packageManager: 'pnpm@10.29.2',
  };

  await writeFile(path.join(targetRoot, 'package.json'), `${JSON.stringify(packageJson, null, 2)}\n`);
  await writeFile(
    path.join(targetRoot, '.env.example'),
    [
      `OPENCLAWD_MERCHANT_LABEL="${options.label}"`,
      `OPENCLAWD_MERCHANT_WALLET=${options.recipient}`,
      `OPENCLAWD_SOLANA_CLUSTER=${options.cluster}`,
      'SOLANA_RPC_URL=https://api.devnet.solana.com',
      'HELIUS_API_KEY=',
      '',
    ].join('\n')
  );
  await writeFile(
    path.join(targetRoot, 'openclawd.merchant.json'),
    `${JSON.stringify(
      {
        name: appName,
        label: options.label,
        recipient: options.recipient,
        cluster: options.cluster,
        currency: options.cluster === 'mainnet-beta' ? 'USDC' : 'SOL',
        generatedFrom: 'payments/pay-main',
      },
      null,
      2
    )}\n`
  );

  const included = includeForType(options.type);
  const encodedLabel = encodeURIComponent(options.label).replace(/%20/g, '+');
  const posDocs = included.includes('point-of-sale')
    ? `## Point of Sale

\`\`\`bash
npm run pos:dev
npm run pos:proxy
open "https://localhost:3001/new?recipient=${options.recipient}&label=${encodedLabel}"
\`\`\`
`
    : '';
  const merchantDocs = included.includes('payment-flow-merchant')
    ? `## Agentic Merchant Flow

\`\`\`bash
npm run merchant:start
\`\`\`
`
    : '';
  await writeFile(
    path.join(targetRoot, 'README.md'),
    `# ${options.label} OpenClawd Merchant

This project was generated from \`payments/pay-main\` and keeps the Solana Pay
core/examples under \`solana-pay/\` so the upstream payment flow remains easy to
diff and update.

## Install

\`\`\`bash
pnpm install
npm run install:templates
\`\`\`

${posDocs}
${merchantDocs}

Use \`openclawd.merchant.json\` as the local manifest for agents that need to
generate store links, create checkout sessions, or validate paid orders.
`
  );
}

async function patchGeneratedPackages(targetRoot, options, appName) {
  const examples = includeForType(options.type);
  if (examples.includes('point-of-sale')) {
    const pkgPath = path.join(targetRoot, 'solana-pay/examples/point-of-sale/package.json');
    const pkg = JSON.parse(await readFile(pkgPath, 'utf8'));
    pkg.name = `@openclawdsolana/${appName}-point-of-sale`;
    pkg.description = `${options.label} Solana point of sale generated by OpenClawd`;
    await writeFile(pkgPath, `${JSON.stringify(pkg, null, 4)}\n`);
  }

  if (examples.includes('payment-flow-merchant')) {
    const pkgPath = path.join(targetRoot, 'solana-pay/examples/payment-flow-merchant/package.json');
    const pkg = JSON.parse(await readFile(pkgPath, 'utf8'));
    pkg.name = `@openclawdsolana/${appName}-payment-flow-merchant`;
    pkg.description = `${options.label} agentic Solana merchant flow generated by OpenClawd`;
    await writeFile(pkgPath, `${JSON.stringify(pkg, null, 4)}\n`);
  }
}

async function main() {
  if (process.argv.includes('--help') || process.argv.includes('-h')) {
    console.log(help);
    return;
  }

  const options = parseArgs(process.argv.slice(2));
  if (options.command !== 'create' || !options.name) {
    console.error(help);
    process.exit(1);
  }

  const appName = slugify(options.name);
  if (!appName) {
    throw new Error('Project name must include at least one letter or number');
  }

  options.label ||= appName;
  const targetRoot = await copyTemplate(options, appName);
  console.log(`Created OpenClawd merchant kit at ${path.relative(process.cwd(), targetRoot)}`);
  console.log('Next steps:');
  console.log(`  cd ${path.relative(process.cwd(), targetRoot)}`);
  console.log('  pnpm install');
  console.log('  npm run install:templates');
  if (includeForType(options.type).includes('point-of-sale')) {
    console.log('  npm run pos:dev');
  }
  if (includeForType(options.type).includes('payment-flow-merchant')) {
    console.log('  npm run merchant:start');
  }
}

main().catch((error) => {
  console.error(`openclawd merchant generator failed: ${error.message}`);
  process.exit(1);
});
